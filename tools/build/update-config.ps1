. (Join-Path $PSScriptRoot '../common.ps1')
$updateConfig = Get-Content (Join-Path $ProjectRoot 'config/app/updates.json') -Raw | ConvertFrom-Json
$updateRepo = [string]$updateConfig.repository
if ($updateRepo -notmatch '^[A-Za-z0-9][A-Za-z0-9_.-]{0,98}/[A-Za-z0-9][A-Za-z0-9_.-]{0,99}$') {
    throw 'Update repository must be owner/name. Do not configure tokens or arbitrary URLs.'
}
$appSpec = Get-Content (Join-Path $ProjectRoot 'src/apps/pay_by_second/pubspec.yaml') -Raw
$appVersionMatch = [regex]::Match($appSpec, '(?m)^version:\s*(\d+\.\d+\.\d+)\+(\d+)\s*$')
if (-not $appVersionMatch.Success) { throw 'Expected version: major.minor.patch+build in pubspec.yaml.' }
$generated = @"
// Generated by tools/build/update-config.ps1; edit config/app/updates.json or pubspec.yaml.
const updateRepository = '$updateRepo';
const applicationVersion = '$($appVersionMatch.Groups[1].Value)';
const applicationBuild = '$($appVersionMatch.Groups[2].Value)';
"@
$target = Join-Path $ProjectRoot 'src/apps/pay_by_second/lib/infrastructure/generated/update_config.dart'
[System.IO.Directory]::CreateDirectory((Split-Path -Parent $target)) | Out-Null
[System.IO.File]::WriteAllText($target, ($generated.Replace("`r`n", "`n").TrimEnd() + "`n"), [System.Text.UTF8Encoding]::new($false))
